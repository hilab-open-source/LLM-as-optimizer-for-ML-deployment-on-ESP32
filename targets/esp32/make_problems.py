# 2) int8 GEMV
# ---------------------------------------------------------------------------

def gemv_problem(name="gemv_int8", M=512, N=512, K=4, seed=1, iters=21):
    rng = np.random.default_rng(seed)
    W = rng.integers(-127, 128, (M, N), dtype=np.int16).astype(np.int8)
    b = rng.integers(-5000, 5000, M, dtype=np.int32)
    X = rng.integers(-127, 128, (K, N), dtype=np.int16).astype(np.int8)
    Y = (b.astype(np.int64)[None, :] + X.astype(np.int64) @ W.astype(np.int64).T).astype(np.int32)
    arch = f"""Operator: int8 GEMV (matrix-vector product), the core of every dense layer.

  y[m] = gemv_bias[m] + sum_n gemv_W[m][n] * x[n]      (int32 accumulate, no requant)
  gemv_W: int8 [{M}][{N}] = {M*N//1024} KB, in flash. x: int8 [{N}]. y: int32 [{M}].

Correctness is exact integer arithmetic. {M*N//1024} KB of weights is far bigger than the
32 KB flash cache and does not fit comfortably in internal SRAM, so the weights stream
from flash on every call: how they are read (32-bit loads, sequential access, fewer
loop-control instructions per MAC) matters as much as the arithmetic.
"""
    write_problem(name, defines=[f"#define M_ROWS {M}", f"#define N_COLS {N}"],
                  params=[("gemv_W", W, "row-major [M_ROWS][N_COLS]"), ("gemv_bias", b, "bias[M_ROWS]")],
                  inputs=X, expected=Y, arch=arch,
                  baseline=(HERE / "templates" / "gemv_baseline.c").read_text(),
                  check={"mode": "exact"}, iters=iters,
                  metric_note=f"ESP32 CPU cycles per {M}x{N} int8 GEMV (median of {iters})")


# ---------------------------------------------------------------------------
# 3) RMSNorm float32 (tolerance gate)
# ---------------------------------------------------------------------------

def rmsnorm_problem(name="rmsnorm_f32", D=1024, K=6, seed=2, eps=1e-5, iters=31):
    rng = np.random.default_rng(seed)
    g = (1.0 + 0.1 * rng.standard_normal(D)).astype(np.float32)
    X = (rng.standard_normal((K, D)) * rng.uniform(0.5, 3.0, (K, 1))).astype(np.float32)
    x64 = X.astype(np.float64)
    Y = (x64 / np.sqrt((x64 * x64).mean(axis=1, keepdims=True) + eps) * g.astype(np.float64)).astype(np.float32)
    atol, rtol = 1e-4, 1e-3
    arch = f"""Operator: RMSNorm over a row of {D} float32 values (the normalization in Llama-style models).

  y[i] = x[i] * rsqrt(mean(x^2) + eps) * rms_gamma[i]          eps = RMS_EPS

Reference computed in float64; a candidate passes if |y - ref| <= {atol} + {rtol}*|ref| for
every element. The ESP32 has a single-precision FPU (float add/mul/madd in hardware;
double is software-emulated and slow, sqrtf/division are multi-cycle).
"""
    write_problem(name, defines=[f"#define D_MODEL {D}", f"#define RMS_EPS {eps}f"],
                  params=[("rms_gamma", g, "learned scale [D_MODEL]")], inputs=X, expected=Y, arch=arch,
                  baseline=(HERE / "templates" / "rmsnorm_baseline.c").read_text(),
                  check={"mode": "tolerance", "atol": atol, "rtol": rtol}, iters=iters,
                  metric_note=f"ESP32 CPU cycles per RMSNorm({D}) row (median of {iters})")


ALL = {
    "mnist_mlp": lambda: mlp_problem("mnist_mlp", "mnist"),
    "scene_mlp": lambda: mlp_problem("scene_mlp", "scene"),
    "gemv_int8": gemv_problem,
    "rmsnorm_f32": rmsnorm_problem,
}

if __name__ == "__main__":
    names = [a for a in sys.argv[1:] if not a.startswith("--")] or list(ALL)
    for n in names:
        print(f"[{n}]")
        ALL[n]()
