"""Generate ESP32 kernel problems under targets/esp32/problems/<name>/.

Each problem dir gets:
  problem.h       the contract the LLM sees: sizes, weight declarations, run_inference()
  kb_data.h       harness-only: test-vector declarations, gate mode, timing iterations
  problem_data.c  weights, test inputs and the expected outputs (the answer key), as
                  C const arrays; generated, not committed (scene_mlp's is ~2 MB)
  arch.txt        what the operator computes, shown to the LLM
  baseline.c      the starting kernel (copied from templates/ once; edit freely)
  spec.json       metadata (sizes, dtypes, gate, metric)

  python -m targets.esp32.make_problems             # all
  python -m targets.esp32.make_problems mnist_mlp   # one

Problems:
  mnist_mlp, scene_mlp  the int8 ResNet-MLPs under models/; answer key = numpy forward_i8 (bit-exact)
  gemv_int8             512x512 int8 weights x int8 vector -> int32 (bit-exact)
  rmsnorm_f32           RMSNorm over 1024 floats with a learned scale (tolerance gate)
"""
from __future__ import annotations

import json
import re
import sys
from pathlib import Path

import numpy as np

REPO = Path(__file__).resolve().parents[2]
if str(REPO) not in sys.path:
    sys.path.insert(0, str(REPO))

HERE = Path(__file__).parent
PROBLEMS = HERE / "problems"
MODELS = REPO / "models"

CTYPE = {"int8": "int8_t", "int32": "int32_t", "float32": "float"}


def c_values(a: np.ndarray) -> str:
    flat = a.reshape(-1)
    if a.dtype == np.float32:
        vals = [f"{float(v):.9g}f" for v in flat]
    else:
        vals = [str(int(v)) for v in flat]
    lines = [", ".join(vals[i:i + 24]) for i in range(0, len(vals), 24)]
    return "{\n  " + ",\n  ".join(lines) + "\n}"


def c_shape(a: np.ndarray) -> str:
    return "".join(f"[{d}]" for d in a.shape)


def write_problem(name: str, *, defines: list[str], params: list[tuple[str, np.ndarray, str]],
                  inputs: np.ndarray, expected: np.ndarray, arch: str, baseline: str,
                  check: dict, iters: int, metric_note: str, extra_h: str = "") -> Path:
    d = PROBLEMS / name
    d.mkdir(parents=True, exist_ok=True)
    in_c, out_c = CTYPE[str(inputs.dtype)], CTYPE[str(expected.dtype)]
    K = inputs.shape[0]

    h = ["/* problem.h: the fixed contract for this kernel (generated by make_problems.py). */",
         "#pragma once", "#include <stdint.h>", "",
         "#if defined(ARDUINO) || defined(ESP_PLATFORM)",
         "#include \"esp_attr.h\"   /* IRAM_ATTR, DRAM_ATTR */",
         "#else",
         "#define IRAM_ATTR",
         "#define DRAM_ATTR",
         "#endif", "",
         "#ifdef __cplusplus", "extern \"C\" {", "#endif", "",
         f"#define INPUT_SIZE  {inputs.shape[1]}", f"#define OUTPUT_SIZE {expected.shape[1]}",
         *defines, "",
         f"typedef {in_c} in_t;", f"typedef {out_c} out_t;", "",
         "/* Parameters: const arrays defined in problem_data.c. Being const, they are placed",
         "   in flash and read through the 32 KB flash cache. */"]
    h += [f"extern const {CTYPE[str(a.dtype)]} {n}{c_shape(a)};   /* {doc} */" for n, a, doc in params]
    h += ["", extra_h.rstrip(), "" if extra_h else None,
          "/* The kernel. Called once per sample; must write all OUTPUT_SIZE outputs. */",
          f"void run_inference(const {in_c} *input, {out_c} *output);", "",
          "#ifdef __cplusplus", "}", "#endif", ""]
    (d / "problem.h").write_text("\n".join(l for l in h if l is not None))

    exact = check["mode"] == "exact"
    kb = ["/* kb_data.h: harness-only data (generated). */", "#pragma once", "#include \"problem.h\"", "",
          "#ifdef __cplusplus", "extern \"C\" {", "#endif",
          f"#define NUM_VECTORS {K}", f"#define KB_ITERS {iters}", "#define KB_WARMUP 3",
          f"#define KB_CHECK_EXACT {1 if exact else 0}",
          f"#define KB_ATOL {check.get('atol', 0)}", f"#define KB_RTOL {check.get('rtol', 0)}",
          f"extern const in_t KB_INPUTS[{K}][INPUT_SIZE];",
          f"extern const out_t KB_EXPECTED[{K}][OUTPUT_SIZE];",
          "#ifdef __cplusplus", "}", "#endif", ""]
    (d / "kb_data.h").write_text("\n".join(kb))

    data = ["/* problem_data.c: parameters + answer key (generated; do not edit). */",
            "#include \"kb_data.h\"", ""]
    for n, a, _ in params:
        data.append(f"const {CTYPE[str(a.dtype)]} {n}{c_shape(a)} = {c_values(a)};\n")
    data.append(f"const in_t KB_INPUTS[{K}][INPUT_SIZE] = {c_values(inputs)};\n")
    data.append(f"const out_t KB_EXPECTED[{K}][OUTPUT_SIZE] = {c_values(expected)};\n")
    (d / "problem_data.c").write_text("\n".join(data))

    (d / "arch.txt").write_text(arch)
    if not (d / "baseline.c").exists() or "--force" in sys.argv:
        (d / "baseline.c").write_text(baseline)
    spec = {"name": name, "entry": "run_inference", "input_size": int(inputs.shape[1]),
            "output_size": int(expected.shape[1]), "num_vectors": K, "in_dtype": str(inputs.dtype),
            "out_dtype": str(expected.dtype), "check": check, "iters": iters, "metric_note": metric_note,
            "params": [{"name": n, "dtype": str(a.dtype), "shape": list(a.shape)} for n, a, _ in params]}
    (d / "spec.json").write_text(json.dumps(spec, indent=2) + "\n")
    kb_size = sum(a.nbytes for _, a, _ in params) / 1024
    print(f"  wrote {d}  ({kb_size:.0f} KB of parameters)")
    return d


# ---------------------------------------------------------------------------
# 1) int8 ResNet-MLPs from the model packages under models/
# ---------------------------------------------------------------------------

def _parse_header(path: Path) -> dict[str, np.ndarray]:
    text = path.read_text()
    out = {}
    for m in re.finditer(r"static const (int8_t|int32_t) (\w+)((?:\[\d+\])+) = (\{.*?\});", text, re.S):
        dtype = np.int8 if m.group(1) == "int8_t" else np.int32
        shape = tuple(int(x) for x in re.findall(r"\[(\d+)\]", m.group(3)))
        nums = np.array([int(x) for x in re.findall(r"-?\d+", m.group(4))], dtype=dtype)
        out[m.group(2)] = nums.reshape(shape)
    return out


def mlp_problem(name: str, model: str, iters: int = 31):
    from models.common.int8_ref import forward_i8
    mdir = MODELS / model
    W = _parse_header(mdir / "model_data.h")
    tv = json.loads((mdir / "test_vectors.json").read_text())
    inputs = np.array(tv["inputs"], dtype=np.int8)
    expected = np.array(tv["expected"], dtype=np.int8)
    ref = np.stack([forward_i8(W, x) for x in inputs]).astype(np.int8)
    assert np.array_equal(ref, expected), f"{model}: test_vectors.json disagrees with forward_i8"
    I, H, O = W["W_stem"].shape[1], W["W_stem"].shape[0], W["W_out"].shape[0]
    names = ["W_stem", "b_stem", "W1a", "b1a", "W1b", "b1b", "W2a", "b2a", "W2b", "b2b", "W_out", "b_out"]
    params = [(n, W[n], "row-major [out][in]" if n.startswith("W") else "bias") for n in names]
    macs = H * I + 4 * H * H + O * H
    wkb = sum(W[n].nbytes for n in names) / 1024

    arch = f"""Model: {model} classifier (ResNet-style int8 MLP), running on the ESP32 CPU.

  Input:     INPUT_SIZE = {I} int8 values per sample
  Stem:      Dense({H}, relu)        W_stem[{H}][{I}], b_stem[{H}]
  ResBlock1: Dense({H},relu) -> Dense({H}) + skip -> relu     (W1a,b1a,W1b,b1b)
  ResBlock2: Dense({H},relu) -> Dense({H}) + skip -> relu     (W2a,b2a,W2b,b2b)
  Output:    Dense({O})               W_out[{O}][{H}], b_out[{O}]  (no relu)
  Work:      {macs:,} int8 multiply-accumulates per sample; {wkb:.0f} KB of weights.

Fixed-point scheme (must be preserved exactly):
  Each dense layer computes acc(int32) = bias + sum(W[int8] * x[int8]), then
  acc >>= 7 (arithmetic shift), then ReLU and clamp to int8 [-128,127]. The output
  head has no ReLU. The residual skip is added AFTER the >>7 requant.
All int8 outputs must be bit-identical to the reference for every one of the
{len(inputs)} test vectors, before and after the timed runs.
"""
    write_problem(name, defines=[f"#define HIDDEN_SIZE {H}"], params=params, inputs=inputs,
                  expected=expected, arch=arch, baseline=(HERE / "templates" / "mlp_baseline.c").read_text(),
                  check={"mode": "exact"}, iters=iters,
                  metric_note=f"ESP32 CPU cycles per inference (median of {iters})")


